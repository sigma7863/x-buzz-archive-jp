const version = "v2-llm";
const dir = join(process.cwd(), "data");
const fs = await import("fs");
const files = fs
  .readdirSync(dir)
  .filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))
  .sort();

let updated = 0;
for (const f of files) {
  const p = join(dir, f);
  const posts = JSON.parse(readFileSync(p, "utf-8")) as BuzzPost[];
  let changed = 0;
  for (const post of posts) {
    const g = MAP[post.id];
    if (g) {
      post.genres = g;
      post.genre_version = version;
      changed++;
    }
  }
  if (changed > 0) {
    writeFileSync(p, JSON.stringify(posts, null, 2) + "\n", "utf-8");
    console.log(`${f}: ${changed}件をLLM分類(v2-llm)`);
    updated += changed;
  }
}
console.log(`完了: ${updated}件をエージェント分類(version=${version})`);

